// Builds lib/countries.js, the country outlines and sample points /api/air
// uses for a countrywide air quality range. Run it by hand when the source
// data changes; nothing runs it at deploy time.
//
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
//   node lib/build-countries.mjs ne_50m_admin_0_countries.geojson
//
// Natural Earth is public domain.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Open-Meteo's global air quality model runs on a grid of about 0.4 degrees, so
// sampling any finer reads the same cells twice.
const MIN_STEP = 0.4;
const TARGET = 30;
const MAX = 40;

const round = n => Math.round(n * 100) / 100;

// Even-odd over every ring of every polygon, which handles holes too.
function contains(polygons, lon, lat) {
  let inside = false;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
          inside = !inside;
        }
      }
    }
  }
  return inside;
}

function samples(polygons, bbox) {
  const [w, s, e, n] = bbox;
  let points = [];
  for (let cells = 4; cells <= 60; cells += 2) {
    const step = Math.max(MIN_STEP, Math.max(e - w, n - s) / cells);
    points = [];
    for (let lon = w + step / 2; lon < e; lon += step) {
      for (let lat = s + step / 2; lat < n; lat += step) {
        if (contains(polygons, lon, lat)) points.push([round(lat), round(lon)]);
      }
    }
    if (points.length >= TARGET || step === MIN_STEP) break;
  }
  if (points.length > MAX) {
    const every = points.length / MAX;
    points = Array.from({ length: MAX }, (_, i) => points[Math.floor(i * every)]);
  }
  return points;
}

const source = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const countries = [];

for (const f of source.features) {
  const code = [f.properties.ISO_A2_EH, f.properties.ISO_A2].find(c => /^[A-Z]{2}$/.test(c || ''));
  if (!code || !f.geometry) continue;

  const raw = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const polygons = raw
    .map(polygon => polygon.map(ring => ring.map(([lon, lat]) => [round(lon), round(lat)])))
    .filter(polygon => polygon[0].length >= 4);

  const all = polygons.flat(2);
  const bbox = [
    Math.min(...all.map(p => p[0])), Math.min(...all.map(p => p[1])),
    Math.max(...all.map(p => p[0])), Math.max(...all.map(p => p[1]))
  ];

  countries.push({ code, bbox, samples: samples(polygons, bbox), polygons });
}

countries.sort((a, b) => a.code.localeCompare(b.code));

const out = fileURLToPath(new URL('./countries.js', import.meta.url));
writeFileSync(out,
  '// Generated by lib/build-countries.mjs from Natural Earth 1:50m admin 0\n' +
  '// countries (public domain). Do not edit by hand.\n' +
  '// { code, bbox: [w, s, e, n], samples: [[lat, lon]], polygons: [[[[lon, lat]]]] }\n' +
  `export default ${JSON.stringify(countries)};\n`);

const sizes = countries.map(c => c.samples.length);
console.log(`${countries.length} countries, ${sizes.filter(n => n === 0).length} with no sample point,`,
  `median ${sizes.sort((a, b) => a - b)[sizes.length >> 1]} samples`);
